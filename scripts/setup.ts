// bun scripts/setup.ts — link the runtime this product builds against.
//
// The guest is bundled by the vendored toolchain but resolved from THIS
// repository: an import of "solid-js" or "@pocketjs/framework/components" in
// shells/*/src walks up to ./node_modules, not into the submodule. So the packages
// vendor/pocketjs already installed are linked here rather than installed a
// second time, which also guarantees one copy of Solid — two would give the
// app a reactive graph the framework does not own.

import { existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { ROOT, VENDOR } from "./paths.ts";

if (!existsSync(resolve(VENDOR, "package.json"))) {
  throw new Error("Pocket Shell setup: initialize vendor/pocketjs first (git submodule update --init)");
}
// The pinned PocketJS names the Bun it runs on (an older Bun cannot load a
// host config), and .bun-version here, the one CI installs, names the same.
const bun = readFileSync(resolve(ROOT, ".bun-version"), "utf8").trim();
const pinned = readFileSync(resolve(VENDOR, ".bun-version"), "utf8").trim();
if (bun !== pinned) {
  throw new Error(`Pocket Shell setup: .bun-version says Bun ${bun}; vendor/pocketjs runs on Bun ${pinned}`);
}
if (Bun.version !== bun) {
  throw new Error(`Pocket Shell setup: this checkout runs on Bun ${bun} (.bun-version); this is Bun ${Bun.version}`);
}

const links = new Map<string, string>([
  ["node_modules/@pocketjs/framework", "vendor/pocketjs"],
  ["node_modules/solid-js", "vendor/pocketjs/node_modules/solid-js"],
  ["node_modules/@napi-rs/canvas", "vendor/pocketjs/node_modules/@napi-rs/canvas"],
  ["node_modules/bun-types", "vendor/pocketjs/node_modules/bun-types"],
  ["node_modules/typescript", "vendor/pocketjs/node_modules/typescript"],
  ["node_modules/@types/bun", "vendor/pocketjs/node_modules/@types/bun"],
  ["node_modules/@types/opentype.js", "vendor/pocketjs/node_modules/@types/opentype.js"],
  ["node_modules/opentype.js", "vendor/pocketjs/node_modules/opentype.js"],
]);

for (const [destination, source] of links) {
  const target = resolve(ROOT, source);
  if (!existsSync(target)) {
    throw new Error(`Pocket Shell setup: missing ${source}; run bun install in vendor/pocketjs`);
  }
  const link = resolve(ROOT, destination);
  mkdirSync(dirname(link), { recursive: true });
  rmSync(link, { recursive: true, force: true });
  symlinkSync(relative(dirname(link), target), link, "dir");
}

// A PocketJS build writes the style table the framework imports, so a clean
// checkout of the submodule does not have one and a typecheck fails on a
// module that only exists after a build. An empty table is the honest state
// before the first build and is replaced by it.
const styles = resolve(VENDOR, "framework/src/styles.generated.ts");
if (!existsSync(styles)) {
  writeFileSync(styles, "// Generated by PocketJS builds.\nexport const STYLE_IDS: Record<string, number> = {};\n");
}

console.log("Pocket Shell setup: runtime links ready");
