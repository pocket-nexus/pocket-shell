//! The guests after app 0, and the veil's mark.
//!
//! App 0 is the application the pocketjs-psp library embeds
//! (POCKETJS_EMBED_BUNDLE, named by POCKETJS_APP_OUTPUT). This script embeds
//! the others, verbatim and 16-byte aligned, as `$OUT_DIR/guests.rs`:
//!
//! - POCKET_SHELL_REGISTRY: a TSV file, one `output<TAB>id<TAB>title` line per
//!   guest in table order. Empty or unset: no guests, a table of one.
//! - POCKET_SHELL_BUNDLES: the directory holding `<output>.pkb` for each
//!   guest; default `packages/` beside the registry.
//! - POCKET_SHELL_VEIL_LOGO: the 128×128 RGBA mark the veil draws; empty or
//!   unset leaves the veil without it.
use std::{
    env, fs,
    path::{Path, PathBuf},
};

fn main() {
    for key in [
        "POCKET_SHELL_REGISTRY",
        "POCKET_SHELL_BUNDLES",
        "POCKET_SHELL_VEIL_LOGO",
        "POCKETJS_APP_OUTPUT",
    ] {
        println!("cargo:rerun-if-env-changed={key}");
    }
    let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let app0 = env::var("POCKETJS_APP_OUTPUT").unwrap_or_default();
    let registry = env::var_os("POCKET_SHELL_REGISTRY")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from);
    let bundles = env::var_os("POCKET_SHELL_BUNDLES")
        .filter(|value| !value.is_empty())
        .map(PathBuf::from);
    assert!(
        registry.is_some() || bundles.is_none(),
        "POCKET_SHELL_BUNDLES requires POCKET_SHELL_REGISTRY"
    );

    let mut table = String::from(
        "// GENERATED by build.rs.\n\
         pub struct EmbeddedGuest { pub output: &'static str, pub id: &'static str, pub title: &'static str, pub bundle: &'static [u8] }\n\
         #[repr(align(16))]\n#[allow(dead_code)]\nstruct Aligned<const N: usize>([u8; N]);\n\
         pub static GUESTS: &[EmbeddedGuest] = &[\n",
    );
    let mut outputs = vec![app0];
    if let Some(registry) = registry {
        println!("cargo:rerun-if-changed={}", registry.display());
        let packages = bundles.unwrap_or_else(|| registry.parent().unwrap_or(Path::new(".")).join("packages"));
        let tsv = fs::read_to_string(&registry)
            .unwrap_or_else(|error| panic!("{}: {error}", registry.display()));
        for (number, line) in tsv.lines().enumerate() {
            if line.trim().is_empty() {
                continue;
            }
            let columns: Vec<&str> = line.split('\t').collect();
            let [output, id, title] = columns[..] else {
                panic!("{}:{}: expected output\\tid\\ttitle", registry.display(), number + 1);
            };
            assert!(
                !output.is_empty()
                    && output.bytes().all(|c| c.is_ascii_alphanumeric() || b"-_.".contains(&c))
                    && output != "."
                    && output != "..",
                "invalid guest output: {output}"
            );
            assert!(!outputs.iter().any(|o| o == output), "the registry repeats output {output}");
            let path = packages.join(format!("{output}.pkb"));
            println!("cargo:rerun-if-changed={}", path.display());
            let bytes = fs::read(&path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
            let index = outputs.len();
            fs::write(out.join(format!("guest{index}.pkb")), &bytes).unwrap();
            table.push_str(&format!(
                "    EmbeddedGuest {{ output: {output:?}, id: {id:?}, title: {title:?}, bundle: {{ static B: Aligned<{}> = Aligned(*include_bytes!(concat!(env!(\"OUT_DIR\"), \"/guest{index}.pkb\"))); &B.0 }} }},\n",
                bytes.len()
            ));
            outputs.push(output.into());
        }
        assert!(outputs.len() > 1, "the registry lists no guest");
    }
    table.push_str("];\n");
    fs::write(out.join("guests.rs"), table).unwrap();

    let logo = env::var("POCKET_SHELL_VEIL_LOGO")
        .ok()
        .filter(|path| !path.is_empty())
        .map(|path| {
            println!("cargo:rerun-if-changed={path}");
            fs::read(&path).unwrap_or_else(|error| panic!("{path}: {error}"))
        })
        .unwrap_or_default();
    assert!(
        logo.is_empty() || logo.len() == 128 * 128 * 4,
        "POCKET_SHELL_VEIL_LOGO must be 128x128 RGBA"
    );
    fs::write(out.join("veil.raw"), logo).unwrap();
}
