// host contract (pocket.host.json) and PocketJS's operation numbers.
//
//   bun devices/3ds/tools/contracts.ts           write the header
//   bun devices/3ds/tools/contracts.ts --check   fail when the header is stale

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { OP } from "../../../vendor/pocketjs/contracts/spec/spec.ts";
import { hashPocketProfile, type PocketProfile } from "../../../vendor/pocketjs/framework/src/profile.ts";
import { profileFactsC } from "../../../vendor/pocketjs/tools/profile-export.ts";
import { THREE_DS_PROFILE } from "./profile.ts";
const profile = THREE_DS_PROFILE;
const HEADER = resolve(import.meta.dir, "../include/pocket_profile.h");

/** The product's profile facts, hash and operation numbers as one header. */
export function threeDsProfileHeader(selected: PocketProfile = profile): string {
  const hash = hashPocketProfile(selected).slice(7).match(/../g)!.map(byte => Number.parseInt(byte, 16));
  const operations = Object.entries(OP).map(([name, code]) => `#define POCKET_3DS_OP_${name} ${code}u`).join("\n");
  return `/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* Generated by devices/3ds/tools/contracts.ts from pocket.host.json. */\n#ifndef POCKET_3DS_PROFILE_H\n#define POCKET_3DS_PROFILE_H\n#include <stdint.h>\n#include "pocket_runtime.h"\n${profileFactsC(selected, "pocket_3ds_profile")}static const uint8_t pocket_3ds_profile_hash[32] = {${hash.join(",")}};\n${operations}\n#endif\n`;
}

export function ensureThreeDsProfileHeader(): void {
  const expected = threeDsProfileHeader();
  if (!existsSync(HEADER) || readFileSync(HEADER, "utf8") !== expected) writeFileSync(HEADER, expected);
}
if (import.meta.main) {
  const expected = threeDsProfileHeader();
  if (process.argv.includes("--check")) {
    if (readFileSync(HEADER, "utf8") !== expected) throw new Error("devices/3ds/include/pocket_profile.h is stale: run bun devices/3ds/tools/contracts.ts");
  } else writeFileSync(HEADER, expected);
}
