// Writes the C and assembly sources that link a .pocket into the firmware
// image, for pocket_shell_compile_app and pocket_shell_embed_package
// (programs/m5stack-tab5/components/pocket_system/project_include.cmake).
//   bun tools/embed-package.ts --package=<file.pocket> --profile=<pocket.host.json>
//       --name=<name> --output-dir=<dir> [--depfile=<file>]
//
// The package is checked as the firmware admits it at start: the container's
// layout, footer and variant hashes (runtime/spec/pocket-package.ts), a
// variant the exported host contract admits (runtime/spec/admission.ts: the
// variants compiled against its profile hash first, then file order) and an
// app id in that variant's plan, which names the app's slot. A package that
// fails stops the build here instead of at boot.
//
// Output, for NAME n:
//   pocketjs_package_n.h  declares `const pocketjs_system_package_t
//                         pocketjs_package_n` (pocket/system.h)
//   pocketjs_package_n.c  defines it: the bytes and their size
//   pocketjs_package_n.S  the package itself, `.incbin` into .rodata at 16-byte
//                         alignment, read from flash in place
// --depfile writes a Make depfile for the .h: the package, the profile and
// the modules of this program.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { BuildInputs, depfile } from "../../../vendor/pocketjs/framework/compiler/build-inputs.ts";
import { hashPocketProfile, readPocketProfile } from "../../../vendor/pocketjs/framework/src/profile.ts";
import { admissionHost, describeRejection, selectVariant } from "../../../runtime/spec/admission.ts";
import { decodePocketPackage, POCKET_SECTION } from "../../../runtime/spec/pocket-package.ts";

const ROOT = resolve(import.meta.dir, "../../..");
const USAGE = "usage: bun tools/embed-package.ts --package=<file.pocket> --profile=<pocket.host.json> --name=<name> --output-dir=<dir> [--depfile=<file>]";

function options(argv: readonly string[]): Map<string, string> {
  const values = new Map<string, string>();
  for (const argument of argv) {
    const match = /^--([a-z-]+)=(.+)$/.exec(argument);
    if (!match) throw new Error(`unknown argument ${argument}\n${USAGE}`);
    values.set(match[1]!, match[2]!);
  }
  for (const name of ["package", "profile", "name", "output-dir"]) {
    if (!values.has(name)) throw new Error(`--${name} is required\n${USAGE}`);
  }
  return values;
}

/** The app id a variant's plan names, as PocketJS reads it for stated
 *  sections: the firmware's slot is the first 16 hex digits of its
 *  SHA-256. */
export function appId(plan: Uint8Array | undefined): string {
  let parsed: unknown;
  try { parsed = plan ? JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(plan)) : undefined; }
  catch { parsed = undefined; }
  const id = (parsed as { app?: { id?: unknown } } | undefined)?.app?.id;
  if (typeof id !== "string" || id.length === 0) throw new Error("the admitted variant's plan names no app id");
  return id;
}

/** A path as an assembler string literal. */
const quoted = (path: string) => `"${path.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

async function main(): Promise<void> {
  const values = options(process.argv.slice(2));
  const name = values.get("name")!;
  if (!/^[a-z][a-z0-9_]*$/.test(name)) throw new Error("--name must match [a-z][a-z0-9_]*");
  const packagePath = resolve(values.get("package")!);
  const profilePath = resolve(values.get("profile")!);
  const outputDirectory = resolve(values.get("output-dir")!);

  const bytes = new Uint8Array(readFileSync(packagePath));
  const pkg = decodePocketPackage(bytes);
  const profile = readPocketProfile(profilePath);
  // The export carries the binding generation the firmware links.
  const exported = JSON.parse(readFileSync(profilePath, "utf8")) as { hostAbi?: unknown };
  const generation = Number.isInteger(exported.hostAbi) ? exported.hostAbi as number : undefined;
  const host = admissionHost(profile, hashPocketProfile(profile), generation);
  if (pkg.variants.length === 0) throw new Error("the package has no variant");
  const selection = selectVariant(pkg, host);
  if (!selection.ok) throw new Error(`${profile.id} does not admit the package: ${describeRejection(selection)}`);
  const id = appId(selection.variant.sections.find((section) => section.kind === POCKET_SECTION.plan)?.bytes);

  const symbol = `pocketjs_package_${name}`;
  const header = join(outputDirectory, `${symbol}.h`);
  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(header, `/* Generated by devices/m5stack/tools/embed-package.ts; do not edit. */
#pragma once

#include "pocket/system.h"

#ifdef __cplusplus
extern "C" {
#endif

/* ${id}, variant ${selection.index} (${selection.variant.target}), ${bytes.length} bytes. */
extern const pocketjs_system_package_t ${symbol};

#ifdef __cplusplus
}
#endif
`);
  writeFileSync(join(outputDirectory, `${symbol}.c`), `/* Generated by devices/m5stack/tools/embed-package.ts; do not edit. */
#include "${symbol}.h"

extern const uint8_t ${symbol}_start[];

const pocketjs_system_package_t ${symbol} = {
    .bytes = ${symbol}_start,
    .size = ${bytes.length}U,
};
`);
  writeFileSync(join(outputDirectory, `${symbol}.S`), `/* Generated by devices/m5stack/tools/embed-package.ts; do not edit. */
.section .rodata.${symbol},"a",@progbits
.balign 16
.global ${symbol}_start
.type ${symbol}_start, @object
${symbol}_start:
.incbin ${quoted(packagePath)}
.global ${symbol}_end
${symbol}_end:
.size ${symbol}_start, ${symbol}_end - ${symbol}_start
`);
  const depfilePath = values.get("depfile");
  if (depfilePath) {
    const inputs = new BuildInputs();
    await inputs.compiler([resolve(import.meta.path)], resolve(ROOT, "vendor/pocketjs"));
    writeFileSync(resolve(depfilePath), depfile(header, [packagePath, profilePath, ...inputs.paths()]));
  }
  console.log(`${symbol}: ${id} for ${selection.variant.target}, ${bytes.length} bytes`);
}

if (import.meta.main) {
  try {
    await main();
  } catch (error) {
    console.error(`embed-package: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
